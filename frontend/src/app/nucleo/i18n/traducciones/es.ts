/**
 * Las bases de plural: `inventario.aplicar` a partir de `inventario.aplicar.uno`.
 *
 * Va por un parametro generico y no directamente sobre `ClaveI18n` porque un
 * condicional solo se reparte sobre cada miembro de la union cuando lo que se
 * comprueba es un parametro de tipo desnudo; escrito sobre el alias, TypeScript
 * lo evalua de una vez y devuelve `never`.
 *
 * Que exista tambien el `.otros` lo comprueba la prueba del servicio.
 */
type BaseDePlural<K> = K extends `${infer Base}.uno` ? Base : never;

export type ClavePlural = BaseDePlural<ClaveI18n>;

